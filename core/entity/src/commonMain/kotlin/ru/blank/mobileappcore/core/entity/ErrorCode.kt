package ru.blank.mobileappcore.core.entity

/**
 * Перечисление стандартных кодов ошибок для унифицированной обработки.
 *
 * Используется в сочетании с [Entity.Error.Type.Code] для типизированного представления ошибок.
 *
 * ## Популярные сценарии ошибок:
 *
 * ### 1. Серверные ошибки (5xx)
 * - `CODE_500` - Внутренняя ошибка сервера
 * ```kotlin
 * Entity.Error(Entity.Error.Type.Code(ErrorCode.CODE_500))
 * ```
 *
 * ### 2. Клиентские ошибки (4xx)
 * - `CODE_400` - Неверный запрос (валидация)
 * - `CODE_403` - Доступ запрещен (авторизация)
 * - `CODE_404` - Ресурс не найден
 * ```kotlin
 * when (error.code) {
 *     ErrorCode.CODE_404 -> showNotFound()
 *     ErrorCode.CODE_403 -> logout()
 * }
 * ```
 *
 * ### 3. Специфичные ошибки
 * - `NULL_DATA` - Отсутствуют ожидаемые данные
 * - `UNKNOWN` - Неизвестная/необработанная ошибка
 */
enum class ErrorCode {
    /**
     * HTTP 500 - Internal Server Error.
     * Сервер столкнулся с непредвиденной ошибкой.
     */
    CODE_500,

    /**
     * HTTP 404 - Not Found.
     * Запрашиваемый ресурс не существует.
     */
    CODE_404,

    /**
     * HTTP 403 - Forbidden.
     * Доступ к ресурсу запрещен (не хватает прав).
     */
    CODE_403,

    /**
     * HTTP 401 - Unauthorized.
     * Ошибка авторизации (неверный токен или его отсутствие).
     */
    CODE_401,

    /**
     * HTTP 400 - Bad Request.
     * Ошибка валидации или неверные параметры запроса.
     */
    CODE_400,

    /**
     * Неизвестная ошибка (резервный код).
     * Используется когда:
     * - Не удалось определить тип ошибки
     * - Ошибка не попадает под другие категории
     */
    UNKNOWN,

    /**
     * Ошибка отсутствия данных.
     * Примеры случаев:
     * - Ответ API вернул `null` там где ожидались данные
     * - Локальная БД не вернула ожидаемую сущность
     */
    NULL_DATA,

    /** Отсутствует интернет соединение. */
    NO_INTERNET_CONNECTION,

    /** Пустой ответ от сервера. */
    EMPTY_RESPONSE,
}

